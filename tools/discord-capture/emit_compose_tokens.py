def hex_to_compose(hex_value: str, alpha: float) -> str:
    h = hex_value.lstrip("#")
    r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
    if abs(alpha - 1.0) < 1e-6:
        return f"Color(0xFF{r:02X}{g:02X}{b:02X})"
    a = round(alpha * 255)
    return f"Color(0x{a:02X}{r:02X}{g:02X}{b:02X})"


